/** Kullanıcı özel senaryo metnini aramadan önce zenginleştirir. */
export function augmentCustomScenarioDraft(draft: string, locale: DemoLocale): string {
  const d = draft.trim();
  if (!d) return d;
  switch (locale) {
    case "en":
      return augmentEN(d);
    case "de":
      return augmentDE(d);
    default:
      return augmentTR(d);
  }
}
